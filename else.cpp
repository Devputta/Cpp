#include<iostream>
using namespace std;

int main(){
    int num =-10;

    if(num >= 0){

        cout << num << endl <<"The number is Positive " << endl;
    }else{
        cout << num << endl <<"The number is Negative " << endl;
    }

    return 0;

}


// output :

// -10
// The number is Negative 