#include<iostream>
using namespace std;

int main(){
    cout << (3>4) << endl; // False -> 0
    cout << (3<4) << endl; // True -> 1
    cout << (3 <= 4) << endl; // True -> 1
    cout << (3 >= 4) << endl; // False -> 0
    cout << (3 == 4) << endl; // False -> 0
    cout << (3 != 4) << endl; // True -> 1


    return 0;
}